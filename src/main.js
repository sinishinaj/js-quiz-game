const subject = localStorage.getItem("subject");
const players = localStorage.getItem("playerAmount");
const questionsAmount = localStorage.getItem("questionAmount");
let questions = [];

if (subject=="Mixed"){
	questions = data["HTML"].concat(data["CSS"].concat(data["JavaScript"]));
}else{
	questions = data[subject];
}
shuffleArray(questions);

let currentQuestion = 0;
let currentAnswer = "";
let currentPlayer = 0;
const colors = ["", "blue", "red", "green", "orange"];
const playerIndicator = document.getElementById('player');
const questionText = document.getElementById('question');
const answerButtons = document.getElementsByClassName('answer');
const animated = document.getElementsByClassName('expanding');
const submitButton = document.getElementById('submit');
const time = document.getElementById('time');
loadQuestion(0);
let scoreBoard = [];
let answeredQuestions = [];
let timer = 16;

for (var i = 0; i < players; i++){
	scoreBoard.push(0);
}

var tick = setInterval(function(){
	timer--;
	time.innerText = timer+" seconds"
	if (timer <= 0){
		submit();
	}
}, 1000);

function selectAnswer(select){
	clearAnswers();
	document.getElementById("answer-select-"+select).classList.add(colors[currentPlayer]);
	currentAnswer = answerButtons[select].innerText;
}

function clearAnswers(){
	for (i = 0; i < 4; i++){
	  var element = document.getElementById("answer-select-"+i);
	  element.className = "button-class answer";
	}
	currentAnswer = "Failed to answer.";
}

function loadQuestion(){
	let question = questions[currentQuestion];
	shuffleArray(question.Answers);
	for (i = 0; i < animated.length; i++){
	  var element = animated[i];
	  element.style.animation = 'none';
	  element.offsetHeight;
	  element.style.animation = null;
	}
	currentPlayer ++;
	if (currentPlayer > players){
		currentPlayer = 1;
	}
	playerIndicator.innerText = `It's Player ${currentPlayer}'s turn.`
	clearAnswers();
	submitButton.className = "button-class "+colors[currentPlayer];
	playerIndicator.className = colors[currentPlayer];
	questionText.innerText = question.Question
	answerButtons[0].innerText = question.Answers[0];
	answerButtons[1].innerText = question.Answers[1];
	answerButtons[2].innerText = question.Answers[2];
	answerButtons[3].innerText = question.Answers[3];
}

function submit(){
	time.innerText = "Begin!"
	timer = 16;
	let question = questions[currentQuestion];
	let answered = question;
	answered["Player"] = currentPlayer;
	answered["ChosenAnswer"] = currentAnswer;
	answeredQuestions.push(answered);
	if (currentAnswer == question.CorrectAnswer){
		scoreBoard[currentPlayer-1] += 10;
	}
	currentQuestion += 1;
	if (currentQuestion < players * questionsAmount) {
		loadQuestion();
	}else{
		localStorage.setItem("scoreBoard", JSON.stringify(scoreBoard));
		localStorage.setItem("answeredQuestions", JSON.stringify(answeredQuestions));
		location.href = "end.html";
	}
}

/* Randomize array in-place using Durstenfeld shuffle algorithm */
function shuffleArray(array) {
    for (var i = array.length - 1; i > 0; i--) {
        var j = Math.floor(Math.random() * (i + 1));
        var temp = array[i];
        array[i] = array[j];
        array[j] = temp;
    }
}
